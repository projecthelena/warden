// DailyUptimeStat holds uptime stats for a single day.
type DailyUptimeStat struct {
	Date          string  `json:"date"`
	Total         int     `json:"totalChecks"`
	Up            int     `json:"-"`
	UptimePercent float64 `json:"uptimePercent"`
}

// GetDailyUptimeStats returns per-day uptime percentages for the last N days.
func (s *Store) GetDailyUptimeStats(monitorID string, days int) ([]DailyUptimeStat, error) {
	if days < 1 || days > 365 {
		return nil, fmt.Errorf("invalid days: must be between 1 and 365")
	}

	var query string
	if s.IsPostgres() {
		query = `
			SELECT
				TO_CHAR(timestamp, 'YYYY-MM-DD') as day,
				COUNT(*) as total,
				SUM(CASE WHEN status = 'up' THEN 1 ELSE 0 END) as up_count
			FROM monitor_checks
			WHERE monitor_id = $1
			AND timestamp >= NOW() - MAKE_INTERVAL(days => $2)
			GROUP BY day
			ORDER BY day ASC
		`
	} else {
		query = `
			SELECT
				DATE(timestamp) as day,
				COUNT(*) as total,
				SUM(CASE WHEN status = 'up' THEN 1 ELSE 0 END) as up_count
			FROM monitor_checks
			WHERE monitor_id = ?
			AND timestamp >= datetime('now', '-' || ? || ' days')
			GROUP BY day
			ORDER BY day ASC
		`
	}

	rows, err := s.db.Query(s.rebind(query), monitorID, days)
	if err != nil {
		return nil, err
	}
	defer func() { _ = rows.Close() }()

	// Collect results from DB into a map for quick lookup
	dayMap := make(map[string]DailyUptimeStat)
	for rows.Next() {
		var stat DailyUptimeStat
		if err := rows.Scan(&stat.Date, &stat.Total, &stat.Up); err != nil {
			return nil, err
		}
		if stat.Total > 0 {
			stat.UptimePercent = (float64(stat.Up) / float64(stat.Total)) * 100.0
		}
		dayMap[stat.Date] = stat
	}

	// Build a complete slice with all days (fill gaps with no-data entries)
	now := time.Now().UTC()
	result := make([]DailyUptimeStat, days)
	for i := 0; i < days; i++ {
		d := now.AddDate(0, 0, -(days - 1 - i))
		dateStr := d.Format("2006-01-02")
		if stat, ok := dayMap[dateStr]; ok {
			result[i] = stat
		} else {
			result[i] = DailyUptimeStat{Date: dateStr, Total: 0, UptimePercent: -1} // -1 = no data
		}
	}

	return result, nil
}

// GetDailyUptimeStatsForMonitors returns per-day uptime for each monitor, read from the
// precomputed rollup table in one query. The public status page calls this on every load,
// so it reads the rollup instead of aggregating raw checks. Each id gets a filled slice,
// one entry per day oldest to newest; a day with no rollup row (no checks that day) is
// marked -1. Today's row is refreshed by the rollup worker, so it can trail by that
// worker's interval.
func (s *Store) GetDailyUptimeStatsForMonitors(ids []string, days int) (map[string][]DailyUptimeStat, error) {
	if days < 1 || days > 365 {
		return nil, fmt.Errorf("invalid days: must be between 1 and 365")
	}
	if len(ids) == 0 {
		return map[string][]DailyUptimeStat{}, nil
	}

	now := time.Now().UTC()
	oldest := now.AddDate(0, 0, -(days - 1)).Format("2006-01-02")

	placeholders := make([]string, len(ids))
	args := make([]interface{}, 0, len(ids)+1)
	for i, id := range ids {
		placeholders[i] = "?"
		args = append(args, id)
	}
	args = append(args, oldest)

	// day is 'YYYY-MM-DD', so a lexical >= is a date range.
	query := fmt.Sprintf(`SELECT monitor_id, day, total, up_count FROM monitor_uptime_daily
		WHERE monitor_id IN (%s) AND day >= ?`, strings.Join(placeholders, ", "))

	rows, err := s.db.Query(s.rebind(query), args...)
	if err != nil {
		return nil, err
	}
	defer func() { _ = rows.Close() }()

	byMonitor := make(map[string]map[string]DailyUptimeStat, len(ids))
	for rows.Next() {
		var monitorID string
		var stat DailyUptimeStat
		if err := rows.Scan(&monitorID, &stat.Date, &stat.Total, &stat.Up); err != nil {
			return nil, err
		}
		if stat.Total > 0 {
			stat.UptimePercent = (float64(stat.Up) / float64(stat.Total)) * 100.0
		}
		if byMonitor[monitorID] == nil {
			byMonitor[monitorID] = make(map[string]DailyUptimeStat)
		}
		byMonitor[monitorID][stat.Date] = stat
	}
	if err := rows.Err(); err != nil {
		return nil, err
	}

	// Every requested id gets an entry, even one with no rollup rows in the window.
	out := make(map[string][]DailyUptimeStat, len(ids))
	for _, id := range ids {
		dayMap := byMonitor[id]
		filled := make([]DailyUptimeStat, days)
		for i := 0; i < days; i++ {
			d := now.AddDate(0, 0, -(days - 1 - i))
			dateStr := d.Format("2006-01-02")
			if stat, ok := dayMap[dateStr]; ok {
				filled[i] = stat
			} else {
				filled[i] = DailyUptimeStat{Date: dateStr, Total: 0, UptimePercent: -1}
			}
		}
		out[id] = filled
	}
	return out, nil
}

// RollupDailyUptime recomputes the daily uptime rollup for every monitor over the last
// `days` calendar days from raw checks, and upserts it. It uses the same aggregation as
// GetDailyUptimeStats, so a rollup row equals what a live query would return for that day.
// Idempotent: recomputing a day overwrites its row. A day with no checks produces no row,
// so the read path renders it as no-data (-1). The worker calls it with a small window to
// refresh recent days and, once at startup, with the retention window to backfill.
func (s *Store) RollupDailyUptime(days int) error {
	if days < 1 {
		return nil
	}

	var query string
	if s.IsPostgres() {
		query = `SELECT monitor_id, TO_CHAR(timestamp, 'YYYY-MM-DD') as day,
				COUNT(*), SUM(CASE WHEN status = 'up' THEN 1 ELSE 0 END)
			FROM monitor_checks
			WHERE timestamp >= NOW() - MAKE_INTERVAL(days => ?)
			GROUP BY monitor_id, day`
	} else {
		query = `SELECT monitor_id, DATE(timestamp) as day,
				COUNT(*), SUM(CASE WHEN status = 'up' THEN 1 ELSE 0 END)
			FROM monitor_checks
			WHERE timestamp >= datetime('now', '-' || ? || ' days')
			GROUP BY monitor_id, day`
	}

	rows, err := s.db.Query(s.rebind(query), days)
	if err != nil {
		return err
	}
	type rollup struct {
		monitorID, day string
		total, up      int
	}
	var rollups []rollup
	for rows.Next() {
		var r rollup
		if err := rows.Scan(&r.monitorID, &r.day, &r.total, &r.up); err != nil {
			_ = rows.Close()
			return err
		}
		rollups = append(rollups, r)
	}
	if err := rows.Err(); err != nil {
		_ = rows.Close()
		return err
	}
	// Close before writing: SQLite won't let us upsert while a read is still open.
	_ = rows.Close()

	if len(rollups) == 0 {
		return nil
	}

	// One transaction for all upserts: on the startup backfill this can be hundreds of rows,
	// and on SQLite a row-per-transaction would be that many fsyncs while holding the single
	// connection.
	tx, err := s.db.Begin()
	if err != nil {
		return err
	}
	upsert := s.rebind(`INSERT INTO monitor_uptime_daily (monitor_id, day, total, up_count)
		VALUES (?, ?, ?, ?)
		ON CONFLICT(monitor_id, day) DO UPDATE SET total = excluded.total, up_count = excluded.up_count`)
	for _, r := range rollups {
		if _, err := tx.Exec(upsert, r.monitorID, r.day, r.total, r.up); err != nil {
			_ = tx.Rollback()
			return err
		}
	}
	return tx.Commit()
}

// PruneDailyRollups drops rollup rows older than the retention window. Historical rollups
// are otherwise frozen (the worker only recomputes recent days), so pruning raw checks
// never corrupts an older bar.
func (s *Store) PruneDailyRollups(days int) error {
	if days < 1 || days > 3650 {
		return fmt.Errorf("invalid retention days: must be between 1 and 3650")
	}
	cutoff := time.Now().UTC().AddDate(0, 0, -days).Format("2006-01-02")
	_, err := s.db.Exec(s.rebind("DELETE FROM monitor_uptime_daily WHERE day < ?"), cutoff)
	return err
}

// toNullInt64 converts an *int to sql.NullInt64 for nullable column storage.
func toNullInt64(v *int) sql.NullInt64 {
	if v == nil {
		return sql.NullInt64{}
	}
	return sql.NullInt64{Int64: int64(*v), Valid: true}
}

func (s *Store) GetLatencyStats(monitorID string, hours int) ([]LatencyPoint, error) {
	// SECURITY: Validate input
	if hours < 1 || hours > 8760 { // Max 1 year
		return nil, fmt.Errorf("invalid hours: must be between 1 and 8760")
	}

	var query string
	var groupBy string

	if s.IsPostgres() {
		if hours <= 1 {
			groupBy = "TO_CHAR(timestamp, 'YYYY-MM-DD HH24:MI:00')"
		} else if hours <= 168 {
			groupBy = "TO_CHAR(timestamp, 'YYYY-MM-DD HH24:00:00')"
		} else {
			groupBy = "TO_CHAR(timestamp, 'YYYY-MM-DD')"
		}
		// Use MAKE_INTERVAL for parameterized interval
		query = fmt.Sprintf(`
			SELECT
				%s as ts_group,
				CAST(AVG(latency) AS INTEGER) as avg_latency,
				MAX(CASE WHEN status != 'up' THEN 1 ELSE 0 END) as failed
			FROM monitor_checks
			WHERE monitor_id = $1
			AND timestamp > NOW() - MAKE_INTERVAL(hours => $2)
			GROUP BY ts_group
			ORDER BY ts_group ASC
		`, groupBy)
	} else {
		if hours <= 1 {
			groupBy = "strftime('%Y-%m-%d %H:%M:00', timestamp)"
		} else if hours <= 168 {
			groupBy = "strftime('%Y-%m-%d %H:00:00', timestamp)"
		} else {
			groupBy = "strftime('%Y-%m-%d', timestamp)"
		}
		query = fmt.Sprintf(`
			SELECT
				%s as ts_group,
				CAST(AVG(latency) AS INTEGER) as avg_latency,
				MAX(CASE WHEN status != 'up' THEN 1 ELSE 0 END) as failed
			FROM monitor_checks
			WHERE monitor_id = ?
			AND datetime(timestamp) > datetime('now', '-' || ? || ' hours')
			GROUP BY ts_group
			ORDER BY ts_group ASC
		`, groupBy)
	}

	var rows *sql.Rows
	var err error
	if s.IsPostgres() {
		rows, err = s.db.Query(query, monitorID, hours)
	} else {
		rows, err = s.db.Query(query, monitorID, hours)
	}
	if err != nil {
		return nil, err
	}
	defer func() { _ = rows.Close() }()

	var points []LatencyPoint
	for rows.Next() {
		var p LatencyPoint
		var tsStr string
		if err := rows.Scan(&tsStr, &p.Latency, &p.Failed); err != nil {
			return nil, err
		}

		// Parse timestamp string
		if len(tsStr) == 10 { // YYYY-MM-DD
			p.Timestamp, _ = time.Parse("2006-01-02", tsStr)
		} else {
			p.Timestamp, _ = time.Parse("2006-01-02 15:04:05", tsStr)
		}
		points = append(points, p)
	}
	return points, nil
}
