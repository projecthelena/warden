// OutageFilter scopes outage lookups to a specific monitor and/or group. Both fields
// are optional; empty strings mean "no filter on this dimension". Used to power the
// IncidentsView filter row and MonitorPage's per-monitor rollup view.
type OutageFilter struct {
	MonitorID string
	GroupID   string
}

func (s *Store) GetActiveOutages() ([]MonitorOutage, error) {
	return s.GetActiveOutagesFiltered(OutageFilter{})
}

func (s *Store) GetActiveOutagesFiltered(f OutageFilter) ([]MonitorOutage, error) {
	query := `
		SELECT o.id, o.monitor_id, o.type, o.summary, o.start_time, m.name, g.name, g.id
		FROM monitor_outages o
		JOIN monitors m ON o.monitor_id = m.id
		JOIN groups g ON m.group_id = g.id
		WHERE o.end_time IS NULL`
	args := []interface{}{}
	if f.MonitorID != "" {
		query += ` AND o.monitor_id = ?`
		args = append(args, f.MonitorID)
	}
	if f.GroupID != "" {
		query += ` AND m.group_id = ?`
		args = append(args, f.GroupID)
	}
	query += ` ORDER BY o.start_time DESC`

	rows, err := s.db.Query(s.rebind(query), args...)
	if err != nil {
		return nil, err
	}
	defer func() { _ = rows.Close() }()

	var outages []MonitorOutage
	for rows.Next() {
		var o MonitorOutage
		if err := rows.Scan(&o.ID, &o.MonitorID, &o.Type, &o.Summary, &o.StartTime, &o.MonitorName, &o.GroupName, &o.GroupID); err != nil {
			return nil, err
		}
		outages = append(outages, o)
	}
	return outages, nil
}

