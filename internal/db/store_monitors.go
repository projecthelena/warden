// CreateEventWithDetails records a monitor event optionally enriched with diagnostic data
// (status code, latency, error message, response body excerpt, response headers).
// Pass nil for details when the event isn't tied to a concrete HTTP response.
func (s *Store) CreateEventWithDetails(monitorID, eventType, message string, d *EventDetails) error {
	var (
		statusCode sql.NullInt64
		latency    sql.NullInt64
		errMsg     sql.NullString
		body       sql.NullString
		headers    sql.NullString
	)
	if d != nil {
		if d.StatusCode > 0 {
			statusCode = sql.NullInt64{Int64: int64(d.StatusCode), Valid: true}
		}
		if d.Latency > 0 {
			latency = sql.NullInt64{Int64: d.Latency, Valid: true}
		}
		if d.ErrorMessage != "" {
			errMsg = sql.NullString{String: d.ErrorMessage, Valid: true}
		}
		if d.ResponseBody != "" {
			body = sql.NullString{String: d.ResponseBody, Valid: true}
		}
		if d.ResponseHeaders != "" {
			headers = sql.NullString{String: d.ResponseHeaders, Valid: true}
		}
	}
	_, err := s.db.Exec(s.rebind(
		`INSERT INTO monitor_events
			(monitor_id, type, message, status_code, latency, error_message, response_body, response_headers)
		 VALUES (?, ?, ?, ?, ?, ?, ?, ?)`),
		monitorID, eventType, message, statusCode, latency, errMsg, body, headers)
	return err
}

